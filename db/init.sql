-- Создаёт базу parking, таблицы, пользователя БД parking_app и тестовые данные.
-- Запуск: psql postgres -v app_password="<пароль из .env>" -f db/init.sql

DROP DATABASE IF EXISTS parking;
DROP ROLE IF EXISTS parking_app;

CREATE DATABASE parking;
\connect parking

CREATE TABLE users (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE parking_zones (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    capacity     INTEGER          NOT NULL CHECK (capacity > 0),
    hourly_price DOUBLE PRECISION NOT NULL CHECK (hourly_price >= 0)
);

-- при удалении владельца, машины или зоны зависимые записи удаляются (ON DELETE CASCADE)
CREATE TABLE vehicles (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    number   VARCHAR(20) NOT NULL UNIQUE,
    owner_id BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE parking_passes (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id BIGINT      NOT NULL REFERENCES vehicles (id) ON DELETE CASCADE,
    zone_id    BIGINT      NOT NULL REFERENCES parking_zones (id) ON DELETE CASCADE,
    valid_from TIMESTAMP   NOT NULL,
    valid_to   TIMESTAMP   NOT NULL,
    status     VARCHAR(20) NOT NULL CHECK (status IN ('ACTIVE', 'CANCELLED'))
);

-- exit_time и amount пустые, пока машина на парковке
CREATE TABLE parking_sessions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id BIGINT    NOT NULL REFERENCES vehicles (id) ON DELETE CASCADE,
    zone_id    BIGINT    NOT NULL REFERENCES parking_zones (id) ON DELETE CASCADE,
    entry_time TIMESTAMP NOT NULL,
    exit_time  TIMESTAMP,
    amount     DOUBLE PRECISION
);

-- пользователь БД для сервиса: может читать и менять данные, но не создавать и не удалять таблицы
CREATE ROLE parking_app LOGIN PASSWORD :'app_password';
GRANT CONNECT ON DATABASE parking TO parking_app;
GRANT USAGE ON SCHEMA public TO parking_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO parking_app;

